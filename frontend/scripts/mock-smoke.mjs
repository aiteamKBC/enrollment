import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const failures = [];
page.on('pageerror', error => failures.push(error.message));
let user = null;
await page.route('**/*', async route => {
  const url = new URL(route.request().url());
  if (url.origin !== 'http://127.0.0.1:4179') return route.abort();
  if (!/^\/(login_api|learner_api|enrolment_api|coach_api|curriculum_api)\//.test(url.pathname)) return route.continue();
  if (url.pathname === '/login_api/me/') return route.fulfill({ status: user ? 200 : 401, json: user ? { user } : { error: 'Authentication required.' } });
  if (url.pathname.includes('/first-session/')) return route.fulfill({ json: { caseOwner: { name: 'Synthetic enrolment officer', email: 'officer@example.invalid' }, booked: false, event: null, startsOn: null, access: 'book', canBook: true } });
  if (url.pathname.includes('/attendance-mode/')) return route.fulfill({ json: { available: true, modes: [] } });
  return route.fulfill({ json: { count: 0, results: [], programmes: [], users: [], coaches: [], slots: [] } });
});
await mkdir('../private/screenshots', { recursive: true });
await page.goto('http://127.0.0.1:4179/login');
await page.getByRole('button', { name: /sign in/i }).first().waitFor();
await page.screenshot({ path: '../private/screenshots/login.png', fullPage: true });
user = { id: 1, email: 'officer@example.invalid', displayName: 'Synthetic officer', role: 'admin', subjectType: 'staff', subjectId: 1, hasPassword: true, lastLoginAt: null, permissions: [], access: 'enrolment', accesses: ['enrolment'], accessHome: '/users', accessWorkspaces: [{ access: 'enrolment', home: '/users' }] };
await page.goto('http://127.0.0.1:4179/users');
await page.getByRole('navigation', { name: 'Enrolment navigation' }).waitFor();
await page.getByRole('link', { name: 'Learners & contacts' }).waitFor();
await page.screenshot({ path: '../private/screenshots/users.png', fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.getByRole('button', { name: 'Toggle navigation' }).click();
if (!await page.getByRole('link', { name: 'Learners & contacts' }).isVisible()) throw new Error('Mobile navigation did not open.');
await page.screenshot({ path: '../private/screenshots/mobile.png', fullPage: true });
await browser.close();
if (failures.length) throw new Error(failures.join('\n'));
console.log('Browser smoke PASS: login, enrolment shell, mobile navigation; all API responses synthetic.');
